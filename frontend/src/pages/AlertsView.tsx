import React, { useState } from 'react';
import { AlertItem } from '../types/disaster';
import { Bell, AlertTriangle, ShieldAlert, Info, Trash2, Filter } from 'lucide-react';

interface AlertsViewProps {
  alerts: AlertItem[];
  onClearAlerts?: () => void;
}

export const AlertsView: React.FC<AlertsViewProps> = ({ alerts, onClearAlerts }) => {
  const [filterSeverity, setFilterSeverity] = useState<string>('ALL');

  const filteredAlerts = alerts.filter(a => {
    if (filterSeverity === 'ALL') return true;
    return a.severity === filterSeverity;
  });

  return (
    <div className="space-y-6 pb-12">
      
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h2 className="text-xl font-black text-white tracking-wide uppercase flex items-center gap-2">
            <Bell className="w-5 h-5 text-red-500" />
            <span>Emergency Alert Command Log</span>
          </h2>
          <p className="text-xs text-gray-400">
            Real-time automated incident dispatch alerts generated by urban risk threshold crossings.
          </p>
        </div>

        <div className="flex items-center gap-3">
          <div className="flex bg-gray-900 p-1 rounded-xl border border-gray-800 text-xs">
            {['ALL', 'CRITICAL', 'WARNING', 'INFO'].map(sev => (
              <button
                key={sev}
                onClick={() => setFilterSeverity(sev)}
                className={`px-3 py-1.5 rounded-lg font-bold text-xs transition-all ${
                  filterSeverity === sev
                    ? sev === 'CRITICAL' ? 'bg-red-950 text-red-300 border border-red-800' :
                      sev === 'WARNING' ? 'bg-amber-950 text-amber-300 border border-amber-800' :
                      'bg-gray-800 text-white border border-gray-700'
                    : 'text-gray-400 hover:text-gray-200'
                }`}
              >
                {sev}
              </button>
            ))}
          </div>

          {onClearAlerts && (
            <button
              onClick={onClearAlerts}
              className="p-2 rounded-xl bg-gray-900 hover:bg-gray-800 border border-gray-800 text-gray-400 hover:text-red-400 transition-colors"
              title="Clear alerts log"
            >
              <Trash2 className="w-4 h-4" />
            </button>
          )}
        </div>
      </div>

      {/* Alerts Feed */}
      <div className="space-y-3">
        {filteredAlerts.length > 0 ? (
          filteredAlerts.map(alert => {
            const isCritical = alert.severity === 'CRITICAL';
            const isWarning = alert.severity === 'WARNING';

            return (
              <div
                key={alert.id}
                className={`p-4 rounded-2xl border transition-all shadow-lg flex items-start justify-between gap-4 ${
                  isCritical ? 'bg-red-950/30 border-red-900/80' :
                  isWarning ? 'bg-amber-950/30 border-amber-900/80' :
                  'bg-gray-900/90 border-gray-800'
                }`}
              >
                <div className="flex items-start gap-3">
                  <div className={`p-2.5 rounded-xl shrink-0 mt-0.5 ${
                    isCritical ? 'bg-red-900/80 text-red-300' :
                    isWarning ? 'bg-amber-900/80 text-amber-300' :
                    'bg-cyan-950 text-cyan-300'
                  }`}>
                    {isCritical ? <ShieldAlert className="w-5 h-5" /> : isWarning ? <AlertTriangle className="w-5 h-5" /> : <Info className="w-5 h-5" />}
                  </div>

                  <div className="space-y-1">
                    <div className="flex items-center gap-2">
                      <h4 className="text-sm font-extrabold text-white">{alert.title}</h4>
                      <span className={`text-[10px] font-black px-2 py-0.5 rounded border uppercase tracking-wider ${
                        isCritical ? 'bg-red-900 text-white border-red-700' :
                        isWarning ? 'bg-amber-900 text-amber-200 border-amber-700' :
                        'bg-gray-800 text-gray-300 border-gray-700'
                      }`}>
                        {alert.severity}
                      </span>
                    </div>

                    <p className="text-xs text-gray-300 leading-relaxed font-medium">
                      {alert.message}
                    </p>

                    <div className="flex items-center gap-3 text-[10px] text-gray-500 font-mono pt-1">
                      <span>DISPATCH TIME: {alert.timestamp}</span>
                      <span>CATEGORY: {alert.category}</span>
                      {alert.zoneId && <span>ZONE: {alert.zoneId.toUpperCase()}</span>}
                    </div>
                  </div>
                </div>
              </div>
            );
          })
        ) : (
          <div className="bg-gray-900 border border-gray-800 rounded-2xl p-8 text-center text-gray-400 text-xs">
            No alerts logged for severity filter "{filterSeverity}".
          </div>
        )}
      </div>

    </div>
  );
};
